async def test_replies_stay_out_of_the_profile(api):
    author, viewer = uuid.uuid4(), uuid.uuid4()
    await given_a_profile(author)
    original = await insert_post(author, "post", NOW)
    await insert_post(author, "respuesta", NOW + timedelta(minutes=1), parent_id=original)

    response = await api.get(f"/users/{author}/posts", headers=signed_in_as(viewer))

    assert [one["content"] for one in response.json()["items"]] == ["post"]


async def test_an_item_has_the_shape_of_a_feed_item(api):
    author, viewer = uuid.uuid4(), uuid.uuid4()
    await given_a_profile(author)
    await insert_post(author, "hola", NOW)

    response = await api.get(f"/users/{author}/posts", headers=signed_in_as(viewer))
    item = response.json()["items"][0]

    assert item["authorId"] == str(author)
    assert {"likesCount", "retweetsCount", "repliesCount", "likedByMe"} <= item.keys()


