"""The posts tab of another user's profile (E2-H14)."""

import uuid
from datetime import UTC, datetime, timedelta

from posts_api.app.pagination import DEFAULT_PAGE_SIZE
from posts_api.infrastructure.database.models import FollowModel, PostModel
from posts_api.main import app
from tests.conftest import requires_services
from tests.integration.conftest import given_a_profile, signed_in_as

pytestmark = requires_services

NOW = datetime(2026, 10, 17, 12, tzinfo=UTC)


async def insert_post(
    author_id: uuid.UUID, content: str, created_at: datetime, *, parent_id: uuid.UUID | None = None
) -> uuid.UUID:
    """Straight into the table: twenty-five posts through the API would hit the rate limit."""
    async with app.state.session_factory() as session:
        post = PostModel(
            author_id=author_id, content=content, created_at=created_at, parent_id=parent_id
        )
        session.add(post)
        # The id is generated by the database: read it before the commit expires it.
        await session.flush()
        post_id = post.id
        await session.commit()
        return post_id


async def insert_follow(follower_id: uuid.UUID, followee_id: uuid.UUID) -> None:
    """An approved follow, as a protected account leaves it after accepting."""
    async with app.state.session_factory() as session:
        session.add(FollowModel(follower_id=follower_id, followee_id=followee_id))
        await session.commit()


async def test_e2_h14_ca2_own_posts_come_newest_first(api):
    author, viewer = uuid.uuid4(), uuid.uuid4()
    await given_a_profile(author)
    for offset, content in enumerate(["primero", "segundo", "tercero"]):
        await insert_post(author, content, NOW + timedelta(minutes=offset))

    response = await api.get(f"/users/{author}/posts", headers=signed_in_as(viewer))

    assert response.status_code == 200
    assert [one["content"] for one in response.json()["items"]] == [
        "tercero",
        "segundo",
        "primero",
    ]


async def test_e2_h14_ca4_pages_are_twenty(api):
    author, viewer = uuid.uuid4(), uuid.uuid4()
    await given_a_profile(author)
    for offset in range(DEFAULT_PAGE_SIZE + 5):
        await insert_post(author, f"post {offset}", NOW + timedelta(minutes=offset))

    first = (await api.get(f"/users/{author}/posts", headers=signed_in_as(viewer))).json()
    second = (
        await api.get(
            f"/users/{author}/posts?cursor={first['nextCursor']}", headers=signed_in_as(viewer)
        )
    ).json()

    assert len(first["items"]) == 20
    assert first["nextCursor"] is not None
    assert len(second["items"]) == 5
    assert second["nextCursor"] is None


async def test_e2_h14_ca3_a_protected_account_is_403_for_a_stranger(api):
    author, viewer = uuid.uuid4(), uuid.uuid4()
    await given_a_profile(author, visibility="protected")
    await insert_post(author, "solo para seguidores", NOW)

    response = await api.get(f"/users/{author}/posts", headers=signed_in_as(viewer))

    assert response.status_code == 403
    assert response.json()["type"].endswith("/account-is-private")


async def test_e2_h14_ca3_an_approved_follower_reads_a_protected_account(api):
    author, viewer = uuid.uuid4(), uuid.uuid4()
    await given_a_profile(author, visibility="protected")
    await given_a_profile(viewer)
    await insert_follow(viewer, author)
    await insert_post(author, "solo para seguidores", NOW)

    response = await api.get(f"/users/{author}/posts", headers=signed_in_as(viewer))

    assert response.status_code == 200
    assert [one["content"] for one in response.json()["items"]] == ["solo para seguidores"]


